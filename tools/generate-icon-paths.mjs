/**
 * Generate SVG glyph table for <Icon> from the icomoon selection.json.
 *
 * Why: icon-font vertical alignment is baseline-driven and the icomoon glyphs
 * sit in the upper half of the em (per-glyph ink offset 0.21~0.40em), so no
 * single translateY can center every icon. SVG icons (SF Symbols / Material /
 * Lucide form) center exactly by construction — this regenerates the icon
 * table as plain SVG path data, one glyph centered on the 1024 grid, keeping
 * the rendered path data identical to what the font drew (visual parity).
 *
 * Usage:   node tools/generate-icon-paths.mjs
 * Input:   src/resources/fonts/selection.json (AM-0 icon source of truth)
 * Output:  src/resources/fonts/icons.generated.ts  (do not hand-edit)
 * Re-run after tools/build-icon-font.mjs whenever the icon set changes.
 */
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const svgPathBounds = require('svg-path-bounds')

const SELECTION = path.resolve('src/resources/fonts/selection.json')
const OUT = path.resolve('src/resources/fonts/icons.generated.ts')
// path data is on the icomoon design grid (~112 units/em, median ratio 112.2)
const GRID = 112
const CENTER = GRID / 2

const cfg = JSON.parse(fs.readFileSync(SELECTION, 'utf8'))
const entries = []
for (const item of cfg.icons) {
  const d = item.icon.paths.join(' ').replace(/\s+/g, ' ').trim()
  const [x1, y1, x2, y2] = svgPathBounds(d)
  const cx = (x1 + x2) / 2
  const cy = (y1 + y2) / 2
  // selection.json paths are Y-up (SF Symbols source relies on the y-flip that
  // svgicons2svgfont applied when building the font). Bake the flip back around
  // the ink center so the SVG renders upright AND stays centered on the grid:
  // y' = (CENTER - cy) + cy*2 - y  ⇔  translate(dx,dy) scale(1,-1) translate(0,-2cy)
  const dx = +(CENTER - cx).toFixed(2)
  const dy = +(CENTER - cy).toFixed(2)
  const t = `translate(${dx} ${dy}) scale(1 -1) translate(0 ${(-2 * cy).toFixed(2)})`
  // comma aliases share one glyph (RNV semantics preserved)
  for (const name of item.properties.name.split(',')) {
    entries.push({ name: name.trim(), d, t })
  }
}

entries.sort((a, b) => a.name.localeCompare(b.name))
const body = entries
  .map(({ name, d, t }) => `  '${name}': { d: '${d}', t: '${t}' },`)
  .join('\n')

const file = `// Generated by tools/generate-icon-paths.mjs from selection.json — do not hand-edit.
// Each glyph is an SVG path centered on the 112-unit design grid (dx/dy translate the raw
// icomoon ink to the grid center), consumed by src/components/common/Icon.tsx.
/* eslint-disable */
export interface IconGlyph {
  d: string
  t: string
}

export const ICON_GLYPHS: Record<string, IconGlyph> = {
${body}
}

export type IconName = keyof typeof ICON_GLYPHS
`

fs.writeFileSync(OUT, file)
console.log(`generated ${OUT} (${entries.length} names, ${cfg.icons.length} glyphs)`)
